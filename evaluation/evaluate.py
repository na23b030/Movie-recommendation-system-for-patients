from __future__ import annotations

import sys
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from recommender.engine import load_default, read_records, norm_genres


def genre_overlap(items):
    if len(items) < 2:
        return None
    genres = [norm_genres(i['genres']) for i in items]
    return mean(len(x & y) / len(x | y) if x | y else 0.0
                for i, x in enumerate(genres) for y in genres[i+1:])


def run():
    engine = load_default(ROOT)
    profiles = read_records(ROOT / 'dataset/patient_profiles.json')
    if len(profiles) != 16:
        raise AssertionError('Expected exactly 15 synthetic cases and 1 no-constraint control')
    rows, full_results, violations, checked = [], {}, [], 0
    diversity, baseline = [], []
    for p in profiles:
        pid = p['profile_id']
        result = engine.recommend(p, top_k=5, diversify=True)
        plain = engine.recommend(p, top_k=5, diversify=False)
        full_results[pid] = result
        banned = {x['movie_id'] for x in result['excluded_candidates']}
        for item in result['recommendations']:
            checked += 1
            if item['movie_id'] in banned or engine._hard_rule_ids(p, engine.by_id[item['movie_id']]):
                violations.append((pid, item['movie_id']))
        a, b = genre_overlap(result['recommendations']), genre_overlap(plain['recommendations'])
        if a is not None:
            diversity.append(a)
        if b is not None:
            baseline.append(b)
        rows.append((pid, result['returned_count'], result['audit']['eligible_count'],
                     result['audit']['excluded_count'], result['audit']['preference_matched_count']))
    if violations:
        raise AssertionError(f'HARD-RULE VIOLATIONS: {violations}')
    assert full_results['P016']['audit']['excluded_count'] == 0
    hard = sum(x['severity'] == 'hard_exclude' for x in engine.rule_definitions)
    sourced = sum(x['justification_type'] == 'sourced' for x in engine.rule_definitions)
    content = [
        '# Evaluation — Patient-Appropriate Movie Recommender', '',
        '## Scope and methodological limits', '',
        'Generated by `python evaluation/evaluate.py` from the checked-in dataset and rules.',
        '15 synthetic profiles plus P016 no-constraint control; 72 curated movies.',
        'No real patient outcome, watch history, click labels, clinician validation, or ground-truth movie relevance is available.',
        'The synthetic profiles use genre preferences and **do not contain free-text interest descriptions**;',
        'thus this run checks hard rules, genre fallback, comfort penalties, and reranking, **not** the learned semantic model.',
        'A real-model semantic smoke test must be run in an environment with the downloaded Sentence Transformer.', '',
        '## Per-profile results', '',
        '| Profile | Recommended | Rule-eligible | Hard-excluded | Preference-qualified |',
        '|---|---:|---:|---:|---:|',
    ]
    content += [f'| {p} | {n} | {e} | {b} | {q} |' for p,n,e,b,q in rows]
    content += [
        '', '## Integrity', '',
        f'- **{checked} returned recommendations; 0 observed hard-rule violations.**',
        f'- **{len(engine.rule_definitions)} rules:** {hard} hard and {len(engine.rule_definitions)-hard} soft;',
        f'  {sourced} marked sourced, {len(engine.rule_definitions)-sourced} marked inferred.',
        f'- Control P016: {full_results["P016"]["audit"]["excluded_count"]} hard-excluded candidates.',
        '- A rule labeled sourced may rely on source context; associated weight/thresholds remain engineering policy, not clinical validation.',
        '- Hard filters run before scoring and after diversity reranking; they cannot be overruled by a taste score.', '',
        '## Scoring architecture and heuristic rationale', '',
        '- Film descriptions are encoded by the pretrained local `sentence-transformers/all-MiniLM-L6-v2` model into normalized vectors; dot product equals cosine similarity. Movie genres and their brief factual premises are the only model inputs.',
        '- For an explicit interest description: semantic similarity **0.72**, requested-genre coverage **0.22**, genre focus **0.06**. Semantics dominates because meaningful preferences need not share exact words.',
        '- For known genres only: coverage **0.80**, genre focus **0.20**. Without free text there is no fabricated semantic query and no pretrained model inference is necessary.',
        '- For a mix of known and unknown genre labels without interest text: semantic similarity **0.60**, coverage **0.32**, focus **0.08**; unknown labels are encoded as a user genre-intent query.',
        '- For only an unknown genre or only a free-text interest: semantic similarity gets **1.0** weight; no unsupported exact genre scores are invented.',
        '- A candidate without an exact genre match must pass a conservative semantic gate: normalized cosine >= **0.27** and, when four or more rule-eligible titles exist, >= catalog-median similarity + **0.05**. These uncalibrated heuristics limit forced weak matches and require validation on human labels.',
        '- Soft penalties are always tracked separately from taste and multiplied by annotated evidence confidence; penalties are not clinical risk probabilities.',
        '- MMR selection uses **0.88 x final-score - 0.12 x similarity-to-previous-selections**. The 12% variety term is small to prioritize taste, but no labeled preference study optimized it.', '',
        '## Diversity diagnostic (descriptive, not recommendation accuracy)', '',
        f'- Mean pairwise Jaccard overlap of recommended movie genres with MMR: {mean(diversity):.3f}' if diversity else '- Insufficient returned lists for genre-diversity estimate.',
        f'- Without MMR: {mean(baseline):.3f}' if baseline else '- Insufficient lists for baseline estimate.',
        '- Lower genre overlap indicates variety, not necessarily better entertainment suitability.', '',
        '## Hand inspections (outputs generated, not assumed)', ''
    ]
    for pid in ('P002','P005','P009','P014'):
        p = next(x for x in profiles if x['profile_id'] == pid)
        result = full_results[pid]
        names = ', '.join(x['title'] for x in result['recommendations']) or '(none)'
        inspections = {
            'P002': 'Age-11 profile retains animation/family/comedy choices after age-rating exclusions; the five suggestions reflect its stated genres rather than a universal safe list. Recorded warnings are not film-wide safety certificates.',
            'P005': 'Drama/mystery/science-fiction themes remain prominent despite a concentration-difficulty soft penalty. Dense plots can be ranked lower, but they are not banned outright.',
            'P009': 'An adult thriller/crime preference yields markedly different films from the pediatric profile. This also exposes the importance of explicit patient avoidances: darkness or violence is not automatically excluded for all adults.',
            'P014': 'The declared bereavement/self-harm/suicide avoidances remove positively tagged films, while comedy/romance/drama preferences still produce candidates. An absent warning is not a verified absence.',
        }
        content += [f'### {pid}: {p.get("scenario", "Synthetic patient")}', '',
                    f'- Recommended: {names}.',
                    f'- Hard exclusions: {result["audit"]["excluded_count"]}; matched candidates: {result["audit"]["preference_matched_count"]}.',
                    '- Observation: ' + inspections[pid], '']
    content += [
        '## Known limitations and red-team findings', '',
        '1. **R-02:** Treating unknown flashing status as a veto for a photosensitive patient is deliberately precautionary; this exact policy is inferred, not externally certified. It causes abstention because none of the 72 titles has verified no-flash clearance.',
        '2. **R-14:** Threat intensity is subjective and weakly supported by indirect distress guidance; its penalty weight is a heuristic, not a clinical threshold.',
        '3. **R-04:** Excluding MPA R for people under 17 ignores guardian context because this application does not record it; a deliberately simplified policy, not a restatement of the rating law.',
        '4. **R-09:** Absence of a content warning is not evidence of absence. The dataset only represents recorded positive observations.',
        '5. **Accessibility:** All availability fields remain unknown, so the system rightly abstains for patients requiring verified subtitles or audio description.',
        '6. **Semantic relevance:** The local pretrained encoder handles meaning beyond lexical overlap, but movie premises are short and unlabeled; scores, genre weights, and match thresholds are heuristics not validated against real user preferences.',
        '7. **Diagnosis and treatment:** The system does not infer symptoms from a diagnosis or medically certify any film. New patient attributes not represented by explicit rules have not been individually evaluated.',
        '8. **Unknown preferences:** The engine abstains on weak semantic evidence instead of forcing five movies. Thresholds need future empirical calibration using human-labeled data.',
        '9. **Unsupported known sensory factors:** The added coverage-abstention policy returns no movie for P013 because sound and visual-motion sensitivities have no dedicated film evidence in the 16-rule table. It is a conservative data-coverage response, NOT a secretly sourced seventeenth clinical rule.', '',
        '## API separation', '',
        '- `POST /recommendations` returns only titles, genres, runtime, rating and a short explanation (or an empty-list message).',
        '- `POST /recommendations/audit` returns the same selections plus feature score breakdowns, all 16 rule results, citations and excluded candidates for Task 6 review.',
        '- For a demonstrable hard-excluded candidate use profile `P014` or `P002`, not the no-constraint control.', '',
        '## Reproduction', '',
        '- `python -m unittest discover -s tests -v`',
        '- `python evaluation/evaluate.py`',
        '- To download/test the local model: `python -m recommender.semantic`',
        '- Submit genuine timestamps, existing source notes and actual incremental Git commits; do not reconstruct history.', '',
    ]
    path = ROOT / 'evaluation' / 'EVALUATION.md'
    path.write_text('\n'.join(content), encoding='utf-8')
    print(f'Wrote {path}; evaluated {len(rows)} profiles, {checked} recommendations, zero hard-rule violations')
    return rows


if __name__ == '__main__':
    run()
